    // MARK: - backfillAllIfNeeded 一括処理

    func testBackfillAllIfNeededGeneratesForAllBooksIndependently() throws {
        let (main, business, _) = QARegressionTestFactory.makeThreeStandardBooks()

        let pastStartDate = Calendar.current.date(byAdding: .month, value: -2, to: Date())!
        var mainFixed = FixedExpenseData(name: "家賃", amount: 80000, categoryName: "食費", dayOfMonth: 1, startDate: pastStartDate)
        mainFixed.bookId = main.book.id
        var businessFixed = FixedExpenseData(name: "事務所家賃", amount: 150000, categoryName: "食費", dayOfMonth: 1, startDate: pastStartDate)
        businessFixed.bookId = business.book.id
        FixedExpenseDataSync.insert(mainFixed)
        FixedExpenseDataSync.insert(businessFixed)

        RecurringEntryGenerator.backfillAllIfNeeded()

        let mainGenerated = ExpenseDataSync.fetchAll().filter { $0.fixedExpenseId == mainFixed.id }
        let businessGenerated = ExpenseDataSync.fetchAll().filter { $0.fixedExpenseId == businessFixed.id }

        XCTAssertFalse(mainGenerated.isEmpty)
        XCTAssertFalse(businessGenerated.isEmpty)
        XCTAssertTrue(mainGenerated.allSatisfy { $0.bookId == main.book.id })
        XCTAssertTrue(businessGenerated.allSatisfy { $0.bookId == business.book.id })
    }
