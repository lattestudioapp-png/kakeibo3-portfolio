    func testCanAddFixedExpense() throws {
        let (main, _, _) = QARegressionTestFactory.makeThreeStandardBooks()

        var fixedExpense = FixedExpenseData(name: "家賃", amount: 80000, categoryName: "食費", dayOfMonth: 1)
        fixedExpense.bookId = main.book.id
        FixedExpenseDataSync.insert(fixedExpense)

        XCTAssertEqual(FixedExpenseDataSync.fetchAll().count, 1)
    }

    func testFixedExpenseIsScopedToCurrentBookOnly() throws {
        let (main, business, _) = QARegressionTestFactory.makeThreeStandardBooks()

        var fixedExpense = FixedExpenseData(name: "家賃", amount: 80000, categoryName: "食費", dayOfMonth: 1)
        fixedExpense.bookId = main.book.id
        FixedExpenseDataSync.insert(fixedExpense)

        let all = FixedExpenseDataSync.fetchAll()
        XCTAssertEqual(all.filter { $0.bookId == main.book.id }.count, 1)
        XCTAssertEqual(all.filter { $0.bookId == business.book.id }.count, 0)
    }

    func testAutoGeneratedFixedExpenseGoesIntoCorrectBook() throws {
        let (main, business, _) = QARegressionTestFactory.makeThreeStandardBooks()

        let pastStartDate = Calendar.current.date(byAdding: .month, value: -2, to: Date())!
        var fixedExpense = FixedExpenseData(name: "家賃", amount: 80000, categoryName: "食費", dayOfMonth: 1, startDate: pastStartDate)
        fixedExpense.bookId = main.book.id
        FixedExpenseDataSync.insert(fixedExpense)

        RecurringEntryGenerator.generateExpenseEntries(for: fixedExpense, methodName: "現金", bookId: main.book.id)

        let generated = ExpenseDataSync.fetchAll().filter { $0.fixedExpenseId == fixedExpense.id }
        XCTAssertFalse(generated.isEmpty)
        XCTAssertTrue(generated.allSatisfy { $0.bookId == main.book.id })

        let businessGenerated = ExpenseDataSync.fetchAll().filter { $0.bookId == business.book.id }
        XCTAssertTrue(businessGenerated.isEmpty)
    }

    func testFixedExpenseGenerationIsIdempotent() throws {
        let (main, _, _) = QARegressionTestFactory.makeThreeStandardBooks()

        let pastStartDate = Calendar.current.date(byAdding: .month, value: -2, to: Date())!
        var fixedExpense = FixedExpenseData(name: "家賃", amount: 80000, categoryName: "食費", dayOfMonth: 1, startDate: pastStartDate)
        fixedExpense.bookId = main.book.id
        FixedExpenseDataSync.insert(fixedExpense)

        RecurringEntryGenerator.generateExpenseEntries(for: fixedExpense, methodName: "現金", bookId: main.book.id)
        let firstRunCount = ExpenseDataSync.fetchAll().filter { $0.fixedExpenseId == fixedExpense.id }.count

        // 同じ設定に対して繰り返し呼んでも重複生成されない
        RecurringEntryGenerator.generateExpenseEntries(for: fixedExpense, methodName: "現金", bookId: main.book.id)
        let secondRunCount = ExpenseDataSync.fetchAll().filter { $0.fixedExpenseId == fixedExpense.id }.count

        XCTAssertEqual(firstRunCount, secondRunCount)
        XCTAssertGreaterThan(firstRunCount, 0)
    }

    func testCanEditAndDeactivateFixedExpense() throws {
        let (main, _, _) = QARegressionTestFactory.makeThreeStandardBooks()
        var fixedExpense = FixedExpenseData(name: "家賃", amount: 80000, categoryName: "食費", dayOfMonth: 1)
        fixedExpense.bookId = main.book.id
        FixedExpenseDataSync.insert(fixedExpense)

        fixedExpense.amount = 85000
        FixedExpenseDataSync.update(fixedExpense)
        XCTAssertEqual(FixedExpenseDataSync.fetchAll().first?.amount, 85000)

        fixedExpense.isActive = false
        FixedExpenseDataSync.update(fixedExpense)
        XCTAssertFalse(FixedExpenseDataSync.fetchAll().first!.isActive)
    }

